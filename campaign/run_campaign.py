def fmt(value, digits=3, unit=""):
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.{digits}f}{unit}"
    return f"{value}{unit}"


def ms(value):
    return "—" if value is None else f"{value * 1000:.0f}"


def gib(value):
    return "—" if not value else f"{value / 2**30:.2f} GiB"


def label(run):
    if run.get("device") is None:
        return run["id"]
    size = run["size"].upper()
    parts = [f"{size} {run['quant'].upper()}", run["device"].upper() if run["device"] != "vulkan"
             else "Vulkan"]
    if run.get("kv"):
        parts.append(f"KV {run['kv']}")
    ex = run.get("extra", {})
    if "batch_size" in ex:
        parts.append(f"batch {ex['batch_size']}")
    if ex.get("threads"):
        parts.append(f"threads {'default (4)' if ex['threads'] == 'none' else ex['threads']}")
    return " · ".join(parts)


