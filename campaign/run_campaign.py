def cpu_threads(ledger):
    """Fastest of the explicit thread counts on the CPU smoke sweep (median latency)."""
    best = None
    for threads in (16, 32):
        rec = ledger["runs"].get(f"cpu-4b-q8_0-f16-T4-threads{threads}")
        median = g(rec, "stats.latency_median_s") if rec else None
        if median is not None and (best is None or median < best[1]):
            best = (threads, median)
    return best[0] if best else 16


