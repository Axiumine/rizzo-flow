# ----------------------------------------------------------------------------- main

def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--render", action="store_true")
    parser.add_argument("--reextract", action="store_true",
                        help="recompute stats of finished runs from their files, then render")
    parser.add_argument("--only", help="comma-separated substrings of run ids")
    parser.add_argument("--limit", type=int)
    args = parser.parse_args()
    runs = plan()
    ledger = load_ledger()
    todo = [r for r in runs if r["id"] not in ledger["runs"]]
    if args.only:
        keys = args.only.split(",")
        todo = [r for r in todo if any(k in r["id"] for k in keys)]
    if args.limit:
        todo = todo[: args.limit]
    if args.dry_run:
        total = 0
        for r in todo:
            total += estimate(r)
            print(f"{r['id']:45s} {r['block']:8s} ~{estimate(r):6.0f}s  "
                  + " ; ".join(" ".join(_short(a) for a in c[0]) for c in commands(r, OUT / r["id"], ledger)))
        print(f"{len(todo)} runs, ~{hms(total)} (plan has {len(runs)} runs)")
        return
    if args.reextract:
        by_id = {r["id"]: r for r in runs}
        for rid, rec in ledger["runs"].items():
            rundir = OUT / rid
            outputs = {f.stem: f.read_text(encoding="utf-8", errors="replace")
                       for f in rundir.glob("*.stdout")}
            rec["stats"] = extract(by_id.get(rid, rec["run"]), rundir, outputs)
            sampler = Sampler.__new__(Sampler)
            sampler.path = rundir / "nvidia-smi.csv"
            rec["nvidia_smi"] = sampler.summary(rec["t0"], rec["t1"], rec["b0"], rec["b1"])
            rec["prometheus"] = prometheus_stats(rec["t0"], rec["t1"], rec["b0"], rec["b1"])
            rec["stderr_tail"] = [redact(line) for line in rec.get("stderr_tail", [])]
        ledger.pop("machine", None)
    if args.render or args.reextract:
        render(ledger, runs)
        return
    OUT.mkdir(parents=True, exist_ok=True)
    check = subprocess.run(
        [str(VENV / "python"), "-c", "from rizzo_flow import llama_release as r; "
         "print(*(r.locate(f).name for f in ('cuda', 'vulkan', 'cpu')))"],
        cwd=ROOT, capture_output=True, text=True)
    names = check.stdout.split()
    for family, name in zip(("cuda", "vulkan", "cpu"), names):
        if not name.endswith(f"-{family}"):
            raise SystemExit(f"--device {family} would load {name}: install the {family} package")
    if len(names) != 3:
        raise SystemExit(f"runtime check failed: {check.stderr.strip()}")

    def stop(signum, frame):
        raise KeyboardInterrupt(f"signal {signum}")

    signal.signal(signal.SIGTERM, stop)
    for run in todo:
        print(f"[{time.strftime('%H:%M:%S')}] start {run['id']}", flush=True)
        record = execute(run, ledger)
        ledger["runs"][run["id"]] = record
        save_ledger(ledger)  # the measurement is safe even if rendering fails below
        try:
            render(ledger, runs)
        except Exception as error:  # a report bug must not stop a 10 h campaign
            with open(CAMPAIGN / "errors.log", "a", encoding="utf-8") as log:
                log.write(f"{time.strftime('%F %T')} render after {run['id']}: {error!r}\n")
        print(f"[{time.strftime('%H:%M:%S')}] done  {run['id']} {record['status']} "
              f"{record['wall_s']:.1f}s exit {record['exit_codes']}", flush=True)


if __name__ == "__main__":
    main()
