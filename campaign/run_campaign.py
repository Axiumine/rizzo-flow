def plan():
    runs = []

    def add(run):
        run.setdefault("kv", None)
        run.setdefault("extra", {})
        runs.append(run)

    add({"id": "T0-unit", "block": "one-off", "suite": "T0", "device": None})
    for pkg in ("cuda", "cpu", "vulkan"):
        add({"id": f"T2-devices-{pkg}", "block": "one-off" if pkg != "vulkan" else "vulkan",
             "suite": "T2", "device": None, "package": pkg})
    add({"id": "T1-integration", "block": "one-off", "suite": "T1", "device": None})
    # The suite loads the smallest Q8_0 on disk (the 1.7B here); repeat it pinned to the 4B.
    add({"id": "T1-integration-4b", "block": "one-off", "suite": "T1", "device": None,
         "pin_4b": True})

    def config_runs(device, size, quant, block, suites, kv=None, extra=None):
        for suite in suites:
            kvname = kv or "f16"
            ex = dict(extra or {})
            if suite == "T7" and device == "cuda" and size == "4b" and quant in ("q8_0", "bf16") \
                    and kv is None:
                ex["direct_states"] = 37  # comparable with the published 13/777 and 1/777
            add({"id": f"{device}-{size}-{quant}-{kvname}-{suite}", "block": block,
                 "suite": suite, "device": device, "size": size, "quant": quant, "kv": kv,
                 "extra": ex})

    core = ["T3", "T4", "T5", "T6", "T7", "T9"]
    for size, quant in WEIGHTS:
        config_runs("cuda", size, quant, "core", core)
    for size, quant in WEIGHTS:
        for kv in ("q8_0", "q4_0"):
            config_runs("cuda", size, quant, "kv", ["T4", "T7"], kv=kv)
    add({"id": "vulkan-4b-q8_0-f16-T4", "block": "vulkan", "suite": "T4", "device": "vulkan",
         "size": "4b", "quant": "q8_0"})
    add({"id": "vulkan-4b-q8_0-f16-T7", "block": "vulkan", "suite": "T7", "device": "vulkan",
         "size": "4b", "quant": "q8_0", "extra": {"direct_states": 37}})
    for batch in (1, 2, 4, 8, 16):
        add({"id": f"cuda-4b-q8_0-f16-T7-batch{batch}", "block": "sweep", "suite": "T7",
             "device": "cuda", "size": "4b", "quant": "q8_0",
             "extra": {"batch_size": batch, "direct_states": 0}})
    # CPU block: threads first (llama.cpp defaults to 4 threads when --threads is unset),
    # then everything else with the fastest thread count found here.
    for threads in (None, 16, 32):
        add({"id": f"cpu-4b-q8_0-f16-T4-threads{threads or 'default'}", "block": "sweep",
             "suite": "T4", "device": "cpu", "size": "4b", "quant": "q8_0",
             "extra": {"threads": threads or "none"}})
    for size, quant in WEIGHTS:
        config_runs("cpu", size, quant, "core", core)
    for size, quant in WEIGHTS:
        for kv in ("q8_0", "q4_0"):
            config_runs("cpu", size, quant, "kv", ["T4", "T7"], kv=kv)
    for batch in (1, 2, 4, 8, 16):
        add({"id": f"cpu-4b-q8_0-f16-T7-batch{batch}", "block": "sweep", "suite": "T7",
             "device": "cpu", "size": "4b", "quant": "q8_0",
             "extra": {"batch_size": batch, "direct_states": 0}})
    ids = [r["id"] for r in runs]
    assert len(ids) == len(set(ids)), "duplicate run ids"
    return runs


def dev_class(run):
    return "cpu" if run.get("device") == "cpu" else "gpu"


def estimate(run):
    suite = run["suite"]
    if suite in ("T0", "T1", "T2"):
        return {"T0": 10, "T1": 90, "T2": 5}[suite]
    cls = dev_class(run)
    key = suite
    if suite == "T7":
        ds = run["extra"].get("direct_states")
        key = "T7d37" if ds == 37 else "T7s" if ds == 0 else "T7"
    base = EST[cls][key] * MULT[cls][(run["size"], run["quant"])]
    if run["device"] == "vulkan":
        base *= 1.6
    return base + BASELINE_S + SETTLE_S


