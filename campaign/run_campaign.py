def commands(run, rundir, ledger):
    """List of (argv, env_extra, label)."""
    suite, ex = run["suite"], run["extra"]
    rizzo, py = str(VENV / "rizzo"), str(VENV / "python")
    threads = []
    if run.get("device") == "cpu":
        t = ex.get("threads")
        if t == "none":
            threads = []
        elif t:
            threads = ["--threads", str(t)]
        else:
            threads = ["--threads", str(cpu_threads(ledger))]
    if suite == "T0":
        return [([str(VENV / "pytest"), "-q"], {}, "pytest")]
    if suite == "T1":
        if run.get("pin_4b"):
            return [([str(VENV / "pytest"), "-q", "-m", "integration", "-p", "pin_4b_plugin"],
                     {"RIZZO_REAL": "1", "PYTHONPATH": str(CAMPAIGN)}, "pytest")]
        return [([str(VENV / "pytest"), "-q", "-m", "integration"], {"RIZZO_REAL": "1"}, "pytest")]
    if suite == "T2":
        pkg = RUNTIMES / f"llama-b11081-linux-x64-{run['package']}"
        return [([rizzo, "devices"], {"RIZZO_LLAMA_DIR": str(pkg)}, "devices")]
    if suite == "T3":
        return [([rizzo, "decide", f"examples/{name}.json", *model_args(run), *threads,
                  "--output", str(rundir / f"decide-{name}.json")], {}, name)
                for name in ("ticket", "house", "numeric")]
    if suite in ("T4", "T5"):
        bench = "smoke" if suite == "T4" else "perturbations"
        return [([rizzo, "evaluate", f"benchmarks/{bench}.jsonl", "--compare-modes",
                  *model_args(run), *threads, "--output", str(rundir / f"{bench}.json")],
                 {}, bench)]
    # The scripts have no --threads flag: on the CPU a wrapper injects the thread count.
    script_env = {"RIZZO_HW_THREADS": threads[1]} if threads else {}
    script = [py, str(CAMPAIGN / "threads_wrapper.py")] if threads else [py]
    if suite == "T6":
        # validate_checkpoint.py has no --kv-type flag either.
        return [([*script, "scripts/validate_checkpoint.py", "--size", run["size"], "--quant",
                  run["quant"], "--device", run["device"], "--output", str(rundir / "validate")],
                 script_env, "validate")]
    if suite == "T7":
        argv = [*script, "scripts/semif_compare.py", "--system", "rizzo", "--semif", str(SEMIF),
                *model_args(run), "--output", str(rundir / "semif")]
        if "batch_size" in ex:
            argv += ["--batch-size", str(ex["batch_size"])]
        if "direct_states" in ex:
            argv += ["--direct-states", str(ex["direct_states"])]
        return [(argv, script_env, "semif")]
    if suite == "T9":
        argv = [*script, "scripts/typed_decisions.py", str(TYPED), "--model",
                str(ROOT / GGUF[(run["size"], run["quant"])]), "--device", run["device"],
                "--output", str(rundir / "typed.json")]
        return [(argv, script_env, "typed")]
    raise ValueError(suite)


def post_commands(run, rundir, ledger):
    """Commands run after the timed window (no telemetry): semif_report for held-out numbers."""
    if run["suite"] != "T7" or not (rundir / "semif" / "report.json").exists():
        return []
    argv = [str(VENV / "python"), "scripts/semif_report.py", str(rundir / "semif"),
            "--semif", str(SEMIF)]
    # Compare like with like: the maintainers' runs all use the default (f16) KV cache.
    pub = PUBLISHED.get((run["device"], run["size"], run["quant"]))
    if pub and (ROOT / pub).exists() and not run.get("kv") and "batch_size" not in run["extra"]:
        argv += ["--against", f"maintainers={ROOT / pub}"]
    baselines = []
    if run.get("kv"):  # KV effect alone: same device, same weights, f16 KV
        baselines.append((f"this-{run['device']}-kv-f16",
                          OUT / f"{run['device']}-{run['size']}-{run['quant']}-f16-T7" / "semif"))
    elif run["device"] != "cuda" and "batch_size" not in run["extra"]:  # device effect alone
        baselines.append(("this-cuda", OUT / f"cuda-{run['size']}-{run['quant']}-f16-T7" / "semif"))
    for name, ours in baselines:
        if (ours / "report.json").exists() and ours != rundir / "semif":
            argv += ["--against", f"{name}={ours}"]
    return [(argv, {}, "semif_report")]


