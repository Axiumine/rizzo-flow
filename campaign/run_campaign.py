def progress(ledger, runs):
    done = [ledger["runs"][r["id"]] for r in runs if r["id"] in ledger["runs"]]
    todo = [r for r in runs if r["id"] not in ledger["runs"]]
    ratio = {}
    for cls in ("gpu", "cpu"):
        act = sum(d["wall_s"] + BASELINE_S + SETTLE_S for d in done if dev_class(d["run"]) == cls
                  and d["run"]["suite"] not in ("T0", "T1", "T2"))
        est = sum(d["estimate_s"] for d in done if dev_class(d["run"]) == cls
                  and d["run"]["suite"] not in ("T0", "T1", "T2"))
        ratio[cls] = act / est if est else 1.0
    remaining = sum(estimate(r) * (ratio[dev_class(r)] if r["suite"] not in ("T0", "T1", "T2")
                                   else 1) for r in todo)
    elapsed = sum(d["wall_s"] + BASELINE_S + SETTLE_S for d in done)
    failed = sum(1 for d in done if d["status"] != "ok")
    return len(done), len(runs), failed, elapsed, remaining, ratio


