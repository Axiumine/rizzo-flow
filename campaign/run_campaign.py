def leftover_model_processes():
    """Other processes of this checkout that may hold a model (never the runner itself)."""
    found = []
    for pid in os.listdir("/proc"):
        if not pid.isdigit() or int(pid) in (os.getpid(), os.getppid()):
            continue
        try:
            cmd = (Path("/proc") / pid / "cmdline").read_bytes().replace(b"\0", b" ").decode()
        except OSError:
            continue
        if str(VENV) in cmd and "run_campaign.py" not in cmd and any(
                k in cmd for k in ("rizzo", "scripts/", "pytest")):
            found.append(f"{pid}: {cmd[:120]}")
    return found


def execute(run, ledger):
    for _ in range(12):  # one model process at a time: wait up to 60 s, then stop
        left = leftover_model_processes()
        if not left:
            break
        time.sleep(5)
    else:
        raise SystemExit(f"another model process is running, stopping: {left}")
    rundir = OUT / run["id"]
    if rundir.exists():  # interrupted earlier: keep the evidence, start clean
        aside = OUT / "_aborted" / f"{run['id']}-{int(time.time())}"
        aside.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(rundir), str(aside))
    rundir.mkdir(parents=True)
    cmds = commands(run, rundir, ledger)
    sampler = Sampler(rundir / "nvidia-smi.csv")
    b0 = time.time()
    time.sleep(BASELINE_S)
    b1 = time.time()
    outputs, exits, cpu_s, maxrss_kib = {}, [], 0.0, 0
    started = time.strftime("%Y-%m-%d %H:%M:%S")
    t0 = time.time()
    proc = None
    try:
        for argv, env_extra, label in cmds:
            env = {**os.environ, **env_extra}
            with open(rundir / f"{label}.stdout", "w", encoding="utf-8") as out, \
                    open(rundir / f"{label}.stderr", "w", encoding="utf-8") as err:
                proc = subprocess.Popen(argv, cwd=ROOT, env=env, stdout=out, stderr=err)
                _, status, usage = os.wait4(proc.pid, 0)
                proc.returncode = os.waitstatus_to_exitcode(status)
            exits.append(proc.returncode)
            cpu_s += usage.ru_utime + usage.ru_stime
            maxrss_kib = max(maxrss_kib, usage.ru_maxrss)
            outputs[label] = (rundir / f"{label}.stdout").read_text(encoding="utf-8", errors="replace")
    finally:  # never leave a model process or the sampler behind (Ctrl-C, SIGTERM)
        if proc is not None and proc.returncode is None:
            proc.terminate()
            try:
                proc.wait(timeout=20)
            except subprocess.TimeoutExpired:
                proc.kill()
        t1 = time.time()
        sampler.stop()
    for argv, env_extra, label in post_commands(run, rundir, ledger):
        with open(rundir / f"{label}.stdout", "w", encoding="utf-8") as out, \
                open(rundir / f"{label}.stderr", "w", encoding="utf-8") as err:
            subprocess.run(argv, cwd=ROOT, env={**os.environ, **env_extra}, stdout=out, stderr=err)
    time.sleep(SETTLE_S)
    wall = t1 - t0
    exp = expected_output(run, rundir)
    if isinstance(exp, list):
        produced = all(p.exists() for p in exp)
    elif exp:
        produced = exp.exists()
    else:  # pytest: "ok" means the suite ran; failing tests are results, listed in stats
        produced = all(code == 0 for code in exits) or (
            run["suite"] in ("T0", "T1") and exits == [1]
            and re.search(r"\d+ (passed|failed)", outputs.get("pytest", "")) is not None)
    stderr_tail = []
    for _, _, label in cmds:
        lines = (rundir / f"{label}.stderr").read_text(encoding="utf-8", errors="replace").splitlines()
        stderr_tail += [f"{label}: {redact(line)}" for line in lines if line.strip()][-5:]
    record = {
        "id": run["id"], "run": run, "started": started, "wall_s": wall,
        "t0": t0, "t1": t1, "b0": b0, "b1": b1,
        "exit_codes": exits, "status": "ok" if produced else "failed",
        "commands": [" ".join(_short(a) for a in argv) for argv, _, _ in cmds],
        "threads": _threads_used(cmds),
        "env": [e for _, e, _ in cmds],
        "stats": extract(run, rundir, outputs) if produced or run["suite"] in ("T0", "T1", "T2") else {},
        "rusage": {"cpu_seconds": cpu_s, "avg_cores": cpu_s / wall if wall else None,
                   "max_rss_gib": maxrss_kib / 2**20},
        "nvidia_smi": sampler.summary(t0, t1, b0, b1),
        "prometheus": prometheus_stats(t0, t1, b0, b1),
        "stderr_tail": stderr_tail,
        "estimate_s": estimate(run),
    }
    (rundir / "metrics.json").write_text(json.dumps(record, indent=2, ensure_ascii=False),
                                         encoding="utf-8")
    return record


def redact(text):
    """Strip local paths and user names from free text that may reach the public report."""
    text = text.replace(str(VENV) + "/", "").replace(str(ROOT) + "/", "")
    text = text.replace(str(Path.home()), "~")
    return re.sub(r"/media/[^\s:'\"]*/", ".../", text)


def _threads_used(cmds):
    for argv, env, _ in cmds:
        if "RIZZO_HW_THREADS" in env:
            return int(env["RIZZO_HW_THREADS"])
        if "--threads" in argv:
            return int(argv[argv.index("--threads") + 1])
    return None


def _short(arg):
    arg = str(arg)
    for prefix, repl in ((str(VENV) + "/", ""), (str(ROOT) + "/", "")):
        if arg.startswith(prefix):
            arg = repl + arg[len(prefix):]
    return arg


