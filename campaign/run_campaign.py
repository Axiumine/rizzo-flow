def prom(query, at):
    url = f"{PROM}/api/v1/query?" + urllib.parse.urlencode({"query": query, "time": f"{at:.3f}"})
    try:
        with urllib.request.urlopen(url, timeout=10) as response:
            data = json.load(response)["data"]["result"]
        return float(data[0]["value"][1]) if data else None
    except Exception:  # Prometheus down: telemetry is optional
        return None


def prometheus_stats(t0, t1, b0, b1):
    """DCGM (1 s) and node_exporter (2 s) over the run window, never padded before t0.
    Runs shorter than 5 s get no DCGM averages (too few samples): use the nvidia-smi figures."""
    if t1 - t0 < 5:
        return {"window_s": t1 - t0, "short_window": True}
    d = math.floor(t1 - t0)
    bd = max(2, math.floor(b1 - b0))
    w = f"[{d}s]"
    energy = None
    e0 = prom(f"DCGM_FI_DEV_TOTAL_ENERGY_CONSUMPTION{{{DCGM}}}", t0)
    e1 = prom(f"DCGM_FI_DEV_TOTAL_ENERGY_CONSUMPTION{{{DCGM}}}", t1)
    if e0 is not None and e1 is not None:
        energy = (e1 - e0) / 1e3
    s = {
        "gpu_power_avg_w": prom(f"avg_over_time(DCGM_FI_DEV_POWER_USAGE{{{DCGM}}}{w})", t1),
        "gpu_power_max_w": prom(f"max_over_time(DCGM_FI_DEV_POWER_USAGE_INSTANT{{{DCGM}}}{w})", t1),
        "gpu_energy_j": energy,
        "gpu_fb_used_max_mib": prom(f"max_over_time(DCGM_FI_DEV_FB_USED{{{DCGM}}}{w})", t1),
        "gpu_util_avg_pct": prom(f"avg_over_time(DCGM_FI_DEV_GPU_UTIL{{{DCGM}}}{w})", t1),
        "gpu_sm_active_avg": prom(f"avg_over_time(DCGM_FI_PROF_SM_ACTIVE{{{DCGM}}}{w})", t1),
        "gpu_dram_active_avg": prom(f"avg_over_time(DCGM_FI_PROF_DRAM_ACTIVE{{{DCGM}}}{w})", t1),
        "gpu_temp_max_c": prom(f"max_over_time(DCGM_FI_DEV_GPU_TEMP{{{DCGM}}}{w})", t1),
        "gpu_sm_clock_avg_mhz": prom(f"avg_over_time(DCGM_FI_DEV_SM_CLOCK{{{DCGM}}}{w})", t1),
        "gpu_power_cap_throttle_s": _div(prom(
            f"increase(DCGM_FI_DEV_CLOCKS_EVENT_REASON_SW_POWER_CAP_NS{{{DCGM}}}{w})", t1), 1e9),
        "gpu_thermal_throttle_s": _div(prom(
            f"increase(DCGM_FI_DEV_CLOCKS_EVENT_REASON_HW_THERM_SLOWDOWN_NS{{{DCGM}}}{w})", t1), 1e9),
        "cpu_util_avg": prom(
            f"1 - avg(rate(node_cpu_seconds_total{{{NODE},mode=\"idle\"}}{w}))", t1),
        "baseline_gpu_power_w": prom(
            f"avg_over_time(DCGM_FI_DEV_POWER_USAGE{{{DCGM}}}[{bd}s])", b1),
        "baseline_gpu_util_pct": prom(f"avg_over_time(DCGM_FI_DEV_GPU_UTIL{{{DCGM}}}[{bd}s])", b1),
        "baseline_fb_used_mib": prom(f"avg_over_time(DCGM_FI_DEV_FB_USED{{{DCGM}}}[{bd}s])", b1),
        "window_s": t1 - t0,
    }
    if s["gpu_energy_j"] is not None and s["baseline_gpu_power_w"] is not None:
        s["gpu_net_energy_j"] = s["gpu_energy_j"] - s["baseline_gpu_power_w"] * (t1 - t0)
    return s


def _div(value, by):
    return None if value is None else value / by


class Sampler:
    FIELDS = ["timestamp", "utilization.gpu", "memory.used", "power.draw.instant",
              "temperature.gpu", "clocks.sm", "clocks_event_reasons.active"]

    def __init__(self, path):
        self.path = path
        self.stream = open(path, "w", encoding="utf-8")
        self.proc = subprocess.Popen(
            ["nvidia-smi", f"--query-gpu={','.join(self.FIELDS)}", "--format=csv,noheader,nounits",
             "-lms", "100"], stdout=self.stream, stderr=subprocess.DEVNULL)

    def stop(self):
        self.proc.send_signal(signal.SIGINT)
        try:
            self.proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            self.proc.kill()
        self.stream.close()

    def summary(self, t0, t1, b0, b1):
        rows = []
        with open(self.path, encoding="utf-8") as stream:
            for rec in csv.reader(stream):
                if len(rec) < 6:
                    continue
                try:
                    ts = datetime.strptime(rec[0].strip(), "%Y/%m/%d %H:%M:%S.%f").timestamp()
                    rows.append((ts, _num(rec[1]), _num(rec[2]), _num(rec[3]), _num(rec[4])))
                except ValueError:
                    continue
        run = [r for r in rows if t0 <= r[0] <= t1]
        base = [r for r in rows if b0 <= r[0] <= b1]

        def agg(sel, i, fn):
            vals = [r[i] for r in sel if r[i] is not None]
            return fn(vals) if vals else None

        mean = lambda v: sum(v) / len(v)  # noqa: E731
        energy = 0.0
        powered = [(r[0], r[3]) for r in run if r[3] is not None]
        for (ta, pa), (tb, pb) in zip(powered, powered[1:]):
            energy += (pa + pb) / 2 * (tb - ta)
        if powered:  # edges: extend the first/last reading to t0/t1
            energy += powered[0][1] * (powered[0][0] - t0) + powered[-1][1] * (t1 - powered[-1][0])
        base_power = agg(base, 3, mean)
        return {
            "energy_j": energy if powered else None,
            "net_energy_j": energy - base_power * (t1 - t0) if powered and base_power else None,
            "samples": len(run),
            "mem_used_max_mib": agg(run, 2, max),
            "mem_used_baseline_mib": agg(base, 2, mean),
            "util_avg_pct": agg(run, 1, mean),
            "util_max_pct": agg(run, 1, max),
            "power_avg_w": agg(run, 3, mean),
            "power_max_w": agg(run, 3, max),
            "power_baseline_w": agg(base, 3, mean),
            "temp_max_c": agg(run, 4, max),
        }


def _num(text):
    try:
        return float(text.strip())
    except ValueError:
        return None


